    private void tblExemplaresMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblExemplaresMouseClicked
        int linhaSelecionada = tblExemplares.getSelectedRow();

        if (linhaSelecionada != -1) {

            idExemplarSelecionado = (Integer) tblExemplares.getValueAt(linhaSelecionada, 0);

            int idJogo = (Integer) tblExemplares.getValueAt(linhaSelecionada, 1);
            String codigoSerie = tblExemplares.getValueAt(linhaSelecionada, 2).toString();
            String statusConservacao = tblExemplares.getValueAt(linhaSelecionada, 3) != null
                    ? tblExemplares.getValueAt(linhaSelecionada, 3).toString() : "";

            String dispTexto = tblExemplares.getValueAt(linhaSelecionada, 4).toString();
            boolean disponivel = "Sim".equalsIgnoreCase(dispTexto) || "true".equalsIgnoreCase(dispTexto);

            txtCodigoSerie.setText(codigoSerie);
            txtStatusConservacao.setText(statusConservacao);
            chkDisponivel.setSelected(disponivel);

            for (int i = 0; i < cmbJogo.getItemCount(); i++) {
                Jogo j = (Jogo) cmbJogo.getModel().getElementAt(i);
                if (j.getId() == idJogo) {
                    cmbJogo.setSelectedIndex(i);
                    break;
                }
            }
        }
    }//GEN-LAST:event_tblExemplaresMouseClicked

    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        Jogo jogoSelecionado = (Jogo) cmbJogo.getSelectedItem();
        String codigoSerie = txtCodigoSerie.getText().trim();
        String statusConservacao = txtStatusConservacao.getText().trim();
        boolean disponivel = chkDisponivel.isSelected(); // Captura o estado do JCheckBox

        if (jogoSelecionado == null) {
            JOptionPane.showMessageDialog(this, "Cadastre e selecione ao menos um jogo no sistema!");
            return;
        }

        if (codigoSerie.isEmpty()) {
            JOptionPane.showMessageDialog(this, "O código de série do exemplar é obrigatório!");
            return;
        }

        Exemplar exemplar = new Exemplar(
                idExemplarSelecionado,
                jogoSelecionado.getId(),
                codigoSerie,
                statusConservacao,
                disponivel
        );

        exemplarDAO.salvar(exemplar);

        limparCampos();
        carregarTabela();
        JOptionPane.showMessageDialog(this, "Exemplar salvo com sucesso!");
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int linhaSelecionada = tblExemplares.getSelectedRow();

        if (linhaSelecionada == -1) {
            JOptionPane.showMessageDialog(this, "Selecione um exemplar na tabela para excluir!");
            return;
        }

        int idExcluir = (Integer) tblExemplares.getValueAt(linhaSelecionada, 0);

        int confirmacao = JOptionPane.showConfirmDialog(
                this,
                "Deseja realmente excluir este exemplar?",
                "Confirmação de Exclusão",
                JOptionPane.YES_NO_OPTION
        );

        if (confirmacao == JOptionPane.YES_OPTION) {
            exemplarDAO.excluir(idExcluir);
            limparCampos();
            carregarTabela();
            JOptionPane.showMessageDialog(this, "Exemplar excluído com sucesso!");
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

