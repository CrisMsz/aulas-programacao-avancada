    private void carregarComboJogos() {
        List<Jogo> lista = jogoDAO.listar();

        DefaultComboBoxModel model = new DefaultComboBoxModel();
        for (Jogo j : lista) {
            model.addElement(j);
        }
        cmbJogo.setModel(model);
    }

    private void carregarTabela() {
        if (tblExemplares == null || tblExemplares.getModel() == null) {
            return;
        }

        List<Exemplar> lista = exemplarDAO.listar();
        DefaultTableModel model = (DefaultTableModel) tblExemplares.getModel();
        model.setRowCount(0);

        for (Exemplar ex : lista) {
            model.addRow(new Object[]{
                ex.getId(),
                ex.getIdJogo(),
                ex.getCodigoSerie(),
                ex.getStatusConservacao(),
                ex.isDisponivel() ? "Sim" : "Não"
            });
        }
    }

    private void limparCampos() {
        idExemplarSelecionado = null;
        txtCodigoSerie.setText("");
        txtStatusConservacao.setText("");
        chkDisponivel.setSelected(true);

        if (cmbJogo.getItemCount() > 0) {
            cmbJogo.setSelectedIndex(0);
        }
    }

