    private void carregarClientes() {
        List<Cliente> clientes = clienteDAO.listar();
        DefaultComboBoxModel model = new DefaultComboBoxModel();
        for (Cliente c : clientes) {
            model.addElement(c);
        }
        cmbCliente.setModel(model);
    }

    private void carregarExemplaresDisponiveis() {
        List<Exemplar> exemplares = locacaoDAO.listarExemplaresDisponiveis();
        DefaultComboBoxModel model = new DefaultComboBoxModel();
        for (Exemplar ex : exemplares) {
            model.addElement(ex);
        }
        cmbExemplar.setModel(model);
    }

    private void atualizarTabelaCarrinho() {
        DefaultTableModel model = (DefaultTableModel) tblCarrinho.getModel();
        model.setRowCount(0);
        double valorTotal = 0.0;

        for (ItemLocacao item : carrinho) {
            model.addRow(new Object[]{
                item.getIdExemplar(),
                item.getValorPagoDiaria()
            });
            valorTotal += item.getValorPagoDiaria();
        }

        lblTotal.setText(String.format("Total: R$ %.2f", valorTotal));
    }

