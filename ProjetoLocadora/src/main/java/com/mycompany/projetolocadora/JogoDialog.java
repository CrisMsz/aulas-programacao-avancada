    private void limparCampos() {
        idJogoSelecionado = null;
        txtNomeJogo.setText("");
        txtGenero.setText("");
        txtValor.setText("");
        if (cmbPlataforma.getItemCount() > 0) {
            cmbPlataforma.setSelectedIndex(0);
        }
    }

    private void carregarComboPlataformas() {
        PlataformaDAO pDAO = new PlataformaDAO();
        List<Plataforma> lista = pDAO.listar();

        DefaultComboBoxModel model = new DefaultComboBoxModel();
        for (Plataforma p : lista) {
            model.addElement(p);
        }
        cmbPlataforma.setModel(model);
    }

    private void carregarTabela() {
        if (tblListar == null || tblListar.getModel() == null) {
            return;
        }

        List<Jogo> lista = jogoDAO.listar();
        DefaultTableModel model = (DefaultTableModel) tblListar.getModel();
        model.setRowCount(0);

        for (Jogo jogo : lista) {
            model.addRow(new Object[]{
                jogo.getId(),
                jogo.getIdPlataforma(),
                jogo.getTitulo(),
                jogo.getGenero(),
                jogo.getValorDiaria()
            });
        }

    }

