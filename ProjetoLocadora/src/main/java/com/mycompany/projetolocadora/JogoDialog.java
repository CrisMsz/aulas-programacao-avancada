    private void tblListarMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblListarMouseClicked
        int linhaSelecionada = tblListar.getSelectedRow();

        if (linhaSelecionada != -1) {
            idJogoSelecionado = (Integer) tblListar.getValueAt(linhaSelecionada, 0);

            int idPlataforma = (Integer) tblListar.getValueAt(linhaSelecionada, 1);
            String titulo = tblListar.getValueAt(linhaSelecionada, 2).toString();
            String genero = tblListar.getValueAt(linhaSelecionada, 3) != null ? tblListar.getValueAt(linhaSelecionada, 3).toString() : "";
            String valorDiaria = tblListar.getValueAt(linhaSelecionada, 4).toString();

            txtNomeJogo.setText(titulo);
            txtGenero.setText(genero);
            txtValor.setText(valorDiaria);

            for (int i = 0; i < cmbPlataforma.getItemCount(); i++) {
                Plataforma p = (Plataforma) cmbPlataforma.getModel().getElementAt(i);
                if (p.getId() == idPlataforma) {
                    cmbPlataforma.setSelectedIndex(i);
                    break;
                }
            }
        }
    }//GEN-LAST:event_tblListarMouseClicked

